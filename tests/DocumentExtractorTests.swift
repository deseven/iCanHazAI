/// Tests for the document extraction engine:
/// [`DocumentClassifier`](src/Documents/DocumentClassifier.swift),
/// [`DocumentExtractor`](src/Documents/DocumentExtractor.swift), and
/// [`TextRecognizer`](src/Documents/TextRecognizer.swift).
///
/// Fixtures are generated at test time (RTF via AppKit, PDF via PDFKit,
/// docx/odt/doc via `textutil`) so the suite is self-contained and runs on
/// any macOS 15+ host without checked-in binaries.
extension AllAppTests {

    // MARK: - Fixture helpers

    /// Generates the document fixtures used across the suite. All files live
    /// in a temp directory that is removed on deinit. MainActor-isolated
    /// because it builds AppKit views/images (NSTextView, NSImage) to
    /// synthesize PDF/PNG fixtures.
    @MainActor
    private final class DocFixtures {
        let dir: String

        // Generated bytes (kept in memory for fast classifier tests).
        let rtf: Data
        let docx: Data
        let odt: Data
        let doc: Data
        let pdfText: Data
        let pdfMultiPage: Data
        let pdfScanned: Data
        let pngWithText: Data
        let html: Data
        let proprietaryText: Data
        let binary: Data

        init() throws {
            let base = NSTemporaryDirectory()
            let name = "ichai-doc-tests-\(UUID().uuidString)"
            let d = (base as NSString).appendingPathComponent(name)
            try FileManager.default.createDirectory(atPath: d, withIntermediateDirectories: true)
            self.dir = d

            // RTF via AppKit.
            let attr = NSAttributedString(string: "Hello RTF\nSecond line of RTF text.")
            self.rtf = try attr.data(
                from: NSRange(location: 0, length: attr.length),
                documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf]
            )

            // DOCX/ODT/DOC via textutil (from the RTF, written to disk so
            // textutil can read it).
            let rtfURL = URL(fileURLWithPath: d).appendingPathComponent("src.rtf")
            try self.rtf.write(to: rtfURL)
            self.docx = try Self.textutil(["-convert", "docx", "-stdout", rtfURL.path])
            self.odt = try Self.textutil(["-convert", "odt", "-stdout", rtfURL.path])
            self.doc = try Self.textutil(["-convert", "doc", "-stdout", rtfURL.path])

            // PDF with a text layer via NSTextView.dataWithPDF(inside:).
            let tv = NSTextView(frame: NSRect(x: 0, y: 0, width: 612, height: 792))
            tv.string = "Page one text content.\nAnother paragraph on page one."
            self.pdfText = tv.dataWithPDF(inside: tv.bounds)

            // Multi-page PDF (two text pages merged via PDFKit).
            let tv2 = NSTextView(frame: NSRect(x: 0, y: 0, width: 612, height: 792))
            tv2.string = "Second page content here."
            let d1 = tv.dataWithPDF(inside: tv.bounds)
            let d2 = tv2.dataWithPDF(inside: tv2.bounds)
            let docA = PDFDocument(data: d1)!
            let docB = PDFDocument(data: d2)!
            let merged = PDFDocument()
            merged.insert(docA.page(at: 0)!, at: 0)
            merged.insert(docB.page(at: 0)!, at: 1)
            self.pdfMultiPage = merged.dataRepresentation()!

            // Scanned/image-only PDF: a PDF whose single page is a rendered
            // image of text (no text layer). Built by drawing text into an
            // NSImage and embedding it as a PDF page via NSImage.
            self.pdfScanned = try Self.makeImageOnlyPDF(text: "OCR ME PLEASE")

            // PNG with rendered text (for standalone image OCR).
            self.pngWithText = try Self.makePNG(text: "IMAGE OCR TEXT")

            // Plain-text-but-not-document formats (must pass through raw).
            self.html = Data("<html><body><h1>Hi</h1></body></html>".utf8)
            self.proprietaryText = Data("WEIRD-FORMAT: payload\nmore lines".utf8)

            // Arbitrary binary (zip magic bytes) — must be rejected.
            self.binary = Data([0x50, 0x4B, 0x03, 0x04, 0x00, 0x00, 0x00, 0x00])
        }

        deinit { try? FileManager.default.removeItem(atPath: dir) }

        /// Runs `/usr/bin/textutil` and returns its stdout. Throws on failure.
        private static func textutil(_ args: [String]) throws -> Data {
            let p = Process()
            p.executableURL = URL(fileURLWithPath: "/usr/bin/textutil")
            p.arguments = args
            let pipe = Pipe()
            p.standardOutput = pipe
            p.standardError = Pipe()
            try p.run()
            p.waitUntilExit()
            guard p.terminationStatus == 0 else {
                throw NSError(domain: "DocFixtures", code: Int(p.terminationStatus),
                              userInfo: [NSLocalizedDescriptionKey: "textutil failed"])
            }
            return pipe.fileHandleForReading.readDataToEndOfFile()
        }

        /// Renders `text` into an NSImage and returns PNG bytes.
        private static func makePNG(text: String) throws -> Data {
            let size = NSSize(width: 400, height: 100)
            let image = NSImage(size: size)
            image.lockFocus()
            let attrs: [NSAttributedString.Key: Any] = [
                .font: NSFont.systemFont(ofSize: 32),
                .foregroundColor: NSColor.black,
            ]
            (text as NSString).draw(at: NSPoint(x: 20, y: 30), withAttributes: attrs)
            image.unlockFocus()
            guard let tiff = image.tiffRepresentation,
                  let rep = NSBitmapImageRep(data: tiff),
                  let png = rep.representation(using: .png, properties: [:]) else {
                throw NSError(domain: "DocFixtures", code: 1,
                              userInfo: [NSLocalizedDescriptionKey: "PNG render failed"])
            }
            return png
        }

        /// Builds a single-page PDF whose page is a full-bleed image of the
        /// rendered text — no text layer, so OCR fallback must fire.
        private static func makeImageOnlyPDF(text: String) throws -> Data {
            let size = NSSize(width: 612, height: 792)
            let image = NSImage(size: size)
            image.lockFocus()
            NSColor.white.setFill()
            NSRect(origin: .zero, size: size).fill()
            let attrs: [NSAttributedString.Key: Any] = [
                .font: NSFont.systemFont(ofSize: 48),
                .foregroundColor: NSColor.black,
            ]
            (text as NSString).draw(at: NSPoint(x: 60, y: 360), withAttributes: attrs)
            image.unlockFocus()
            guard let tiff = image.tiffRepresentation,
                  let rep = NSBitmapImageRep(data: tiff),
                  let cgImage = rep.cgImage(forProposedRect: nil, context: nil, hints: nil) else {
                throw NSError(domain: "DocFixtures", code: 1,
                              userInfo: [NSLocalizedDescriptionKey: "image render failed"])
            }
            // Draw the rasterized image into a single-page PDF via Core
            // Graphics. The page has no text layer — only pixels — so the
            // extractor's OCR fallback must fire.
            let pdfData = NSMutableData()
            guard let consumer = CGDataConsumer(data: pdfData as CFMutableData) else {
                throw NSError(domain: "DocFixtures", code: 2,
                              userInfo: [NSLocalizedDescriptionKey: "consumer failed"])
            }
            var mediaBox = CGRect(x: 0, y: 0, width: 612, height: 792)
            guard let ctx = CGContext(consumer: consumer, mediaBox: &mediaBox, nil) else {
                throw NSError(domain: "DocFixtures", code: 3,
                              userInfo: [NSLocalizedDescriptionKey: "ctx failed"])
            }
            let pageDict: CFDictionary? = nil
            ctx.beginPDFPage(pageDict)
            ctx.draw(cgImage, in: mediaBox)
            ctx.endPDFPage()
            ctx.closePDF()
            return pdfData as Data
        }
    }

    // MARK: - Classification

    @Suite("Document classifier")
    @MainActor
    struct DocumentClassifierTests {
        @Test("text formats pass through as .text")
        func textPassthrough() async throws {
            let f = try DocFixtures()
            // HTML is plain text — never converted.
            #expect(DocumentClassifier.classify(data: f.html, hint: .init(filename: "page.html")) == .text)
            #expect(DocumentClassifier.classify(data: Data("{\"a\":1}".utf8), hint: .init(filename: "a.json")) == .text)
            #expect(DocumentClassifier.classify(data: Data("<?xml version=\"1.0\"?><r/>".utf8), hint: .init(filename: "a.xml")) == .text)
            // Proprietary-but-textual format is accepted as-is.
            #expect(DocumentClassifier.classify(data: f.proprietaryText, hint: .init(filename: "weird.xyz")) == .text)
        }

        @Test("document binaries classify by extension hint")
        func documentByExtension() async throws {
            let f = try DocFixtures()
            #expect(DocumentClassifier.classify(data: f.rtf, hint: .init(filename: "a.rtf")) == .document(.rtf))
            #expect(DocumentClassifier.classify(data: f.docx, hint: .init(filename: "a.docx")) == .document(.docx))
            #expect(DocumentClassifier.classify(data: f.odt, hint: .init(filename: "a.odt")) == .document(.odt))
            #expect(DocumentClassifier.classify(data: f.doc, hint: .init(filename: "a.doc")) == .document(.doc))
            #expect(DocumentClassifier.classify(data: f.pdfText, hint: .init(filename: "a.pdf")) == .document(.pdf))
        }

        @Test("PDF is detected by magic bytes without a hint")
        func pdfMagicBytes() async throws {
            let f = try DocFixtures()
            #expect(DocumentClassifier.classify(data: f.pdfText, hint: .none) == .document(.pdf))
            #expect(DocumentClassifier.classify(data: f.pdfMultiPage, hint: .none) == .document(.pdf))
        }

        @Test("image binaries classify as .image")
        func imageBucket() async throws {
            let f = try DocFixtures()
            #expect(DocumentClassifier.classify(data: f.pngWithText, hint: .init(filename: "shot.png")) == .image)
        }

        @Test("unknown binaries are rejected as .unsupportedBinary")
        func unsupportedBinary() async throws {
            let f = try DocFixtures()
            #expect(DocumentClassifier.classify(data: f.binary, hint: .init(filename: "a.zip")) == .unsupportedBinary)
        }

        @Test("RTF classifies as document despite being text-bytes")
        func rtfIsDocumentNotText() async throws {
            let f = try DocFixtures()
            // RTF is text-bytes but must be extracted, not passed raw.
            let kind = DocumentClassifier.classify(data: f.rtf, hint: .init(filename: "a.rtf"))
            #expect(kind == .document(.rtf))
        }

        @Test("text with multi-byte UTF-8 characters classifies as text")
        func multiByteUtf8Text() {
            // Rich in ─ (U+2500, 3-byte UTF-8) — the kind of content that
            // broke the old strict-UTF-8-decode-on-sample heuristic when a
            // multi-byte sequence straddled the 8 KB sample boundary.
            let line = "# ─── section ───\n"
            let data = Data(String(repeating: line, count: 800).utf8)
            #expect(data.count > 8192)
            #expect(DocumentClassifier.classify(data: data, hint: .none) == .text)
        }

        @Test("NUL byte in sample is classified as non-text")
        func nulByteBinary() {
            #expect(DocumentClassifier.classify(data: Data("hello\0world".utf8), hint: .none) != .text)
        }

        @Test("high control-byte ratio is classified as non-text")
        func controlByteRatio() {
            var data = Data()
            data.append(Data(repeating: 0x01, count: 400))
            data.append(Data(repeating: 0x61, count: 600))
            #expect(DocumentClassifier.classify(data: data, hint: .none) != .text)
        }
    }

